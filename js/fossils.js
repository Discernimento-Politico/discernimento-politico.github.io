function initFossilsModule() {
  const tabsNav = document.getElementById("timelineTabs");
  const contentContainer = document.getElementById("autopsyContent");

  if (!tabsNav || !contentContainer) return;

  // Render navigation buttons
  tabsNav.innerHTML = fossilsData.map((f, idx) => `
    <button class="dossier-nav-btn ${idx === 0 ? 'active' : ''}" data-fossil-id="${f.id}">
      <span>${f.name}</span>
      <span class="btn-date">${f.year}</span>
    </button>
  `).join('');

  // Event Listeners for Nav
  tabsNav.querySelectorAll(".dossier-nav-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      tabsNav.querySelectorAll(".dossier-nav-btn").forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      const fossilId = btn.getAttribute("data-fossil-id");
      renderDossierView(fossilId);
    });
  });

  // Initial Render
  renderDossierView(fossilsData[0].id);
}

function renderDossierView(fossilId) {
  const fossil = fossilsData.find(f => f.id === fossilId) || fossilsData[0];
  const container = document.getElementById("autopsyContent");
  if (!container) return;

  container.innerHTML = `
    <div class="dossier-view-panel animate-fade-in">
      <div class="dossier-header">
        <div class="dossier-header-title">
          <span class="academic-tag sepia">${fossil.category}</span>
          <h3>${fossil.name}</h3>
          <span style="font-family: var(--font-mono); font-size: 0.85rem; color: var(--text-muted);">
            Período Documentado: ${fossil.year}
          </span>
        </div>
        <div>
          <button class="btn btn-outline btn-sm open-source-btn" data-source-id="${fossil.aberration.primarySourceId}">
            Consultar Documento da Fonte Primária →
          </button>
        </div>
      </div>

      <div class="dossier-sections-stack">
        <!-- Section I -->
        <div class="dossier-section-block">
          <div class="dossier-block-label">${fossil.archaicContext.title}</div>
          <p>${fossil.archaicContext.desc}</p>
        </div>

        <!-- Section II -->
        <div class="dossier-section-block">
          <div class="dossier-block-label">${fossil.aberration.title}</div>
          <ul class="dossier-points-list">
            ${fossil.aberration.points.map(pt => `<li>${pt}</li>`).join('')}
          </ul>
        </div>

        <!-- Section III -->
        <div class="dossier-section-block">
          <div class="dossier-block-label">${fossil.verdict.title}</div>
          <p style="color: var(--text-primary); font-weight: 500;">${fossil.verdict.desc}</p>
        </div>
      </div>
    </div>
  `;

  // Attach event listener to the primary source button
  const sourceBtn = container.querySelector(".open-source-btn");
  if (sourceBtn) {
    sourceBtn.addEventListener("click", () => {
      const srcId = sourceBtn.getAttribute("data-source-id");
      if (window.openSourceDrawer) {
        window.openSourceDrawer(srcId);
      }
    });
  }
}

window.initFossilsModule = initFossilsModule;
